# ── Convenience accessor ──────────────────────────────────────────────────

def get_species(name: str) -> dict:
    """Return the NASA-7 data block for a species. Raises KeyError if unknown."""
    if name not in SPECIES_DATA:
        raise KeyError(
            f"Species '{name}' not in NASA-7 database. "
            f"Available: {list(SPECIES_DATA.keys())}"
        )
    return SPECIES_DATA[name]
